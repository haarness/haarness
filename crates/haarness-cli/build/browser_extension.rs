//! Turns a built Haarness for Chrome (`apps/browser-extension/dist/chrome`)
//! into Rust source that includes every file in the executable, so a CLI
//! release can set Chrome up without Desktop. `build.rs` writes it to
//! `OUT_DIR` when `HAARNESS_EMBED_BROWSER_EXTENSION` names the folder; the
//! crate's tests call it on a fixture folder.

use std::{
    fmt::Write as _,
    fs,
    path::{Component, Path},
};

/// The most the embedded files may weigh together. The extension is well
/// under a megabyte; anything near this is a wrong folder.
pub const MAX_BYTES: u64 = 8 * 1024 * 1024;

/// One file to include: its name inside the extension (`/`-separated) and
/// the absolute path `include_bytes!` reads.
#[derive(Debug, PartialEq, Eq)]
pub struct File {
    pub name: String,
    pub path: String,
}

/// The source for a build without the extension.
pub fn empty() -> String {
    render(&[])
}

/// The source that embeds the extension at `root`: an absolute folder with
/// a `manifest.json`, holding only folders and regular files.
pub fn source(root: &Path) -> Result<String, String> {
    Ok(render(&files(root)?))
}

/// Every file under `root`, sorted by name.
pub fn files(root: &Path) -> Result<Vec<File>, String> {
    if !root.is_absolute() {
        return Err(format!(
            "HAARNESS_EMBED_BROWSER_EXTENSION must be an absolute path, not {}",
            root.display()
        ));
    }
    if !root.join("manifest.json").is_file() {
        return Err(format!(
            "{} has no manifest.json; build the extension first (npm run extension:build)",
            root.display()
        ));
    }
    let mut files = Vec::new();
    let mut total = 0;
    walk(root, root, &mut files, &mut total)?;
    files.sort_by(|left, right| left.name.cmp(&right.name));
    Ok(files)
}

fn walk(root: &Path, folder: &Path, files: &mut Vec<File>, total: &mut u64) -> Result<(), String> {
    let entries = fs::read_dir(folder).map_err(|error| format!("{}: {error}", folder.display()))?;
    for entry in entries {
        let entry = entry.map_err(|error| format!("{}: {error}", folder.display()))?;
        let path = entry.path();
        // Not `metadata`: a link is refused, never followed.
        let kind =
            fs::symlink_metadata(&path).map_err(|error| format!("{}: {error}", path.display()))?;
        if kind.is_dir() {
            walk(root, &path, files, total)?;
            continue;
        }
        if !kind.is_file() {
            return Err(format!(
                "{} is a link or special file; the extension may hold only folders and files",
                path.display()
            ));
        }
        *total += kind.len();
        if *total > MAX_BYTES {
            return Err(format!(
                "{} holds more than {MAX_BYTES} bytes; that is not Haarness for Chrome",
                root.display()
            ));
        }
        let relative = path
            .strip_prefix(root)
            .map_err(|_| format!("{} is outside {}", path.display(), root.display()))?;
        let mut parts = Vec::new();
        for component in relative.components() {
            match component {
                Component::Normal(part) => parts.push(
                    part.to_str()
                        .filter(|part| !part.contains(['/', '\\']))
                        .ok_or_else(|| format!("{} has an unusable name", path.display()))?,
                ),
                _ => return Err(format!("{} has an unusable name", path.display())),
            }
        }
        files.push(File {
            name: parts.join("/"),
            path: path
                .to_str()
                .ok_or_else(|| format!("{} is not valid UTF-8", path.display()))?
                .to_owned(),
        });
    }
    Ok(())
}

fn render(files: &[File]) -> String {
    let mut source = String::from(
        "// Generated by build.rs from HAARNESS_EMBED_BROWSER_EXTENSION; do not edit.\n\
         pub(crate) static FILES: &[(&str, &[u8])] = &[\n",
    );
    for file in files {
        // `{:?}` writes a Rust string literal, escapes and all.
        let _ = writeln!(
            source,
            "    ({:?}, include_bytes!({:?})),",
            file.name, file.path
        );
    }
    source.push_str("];\n");
    source
}
