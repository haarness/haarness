//! Haarness for Chrome built into this executable. Release builds set
//! `HAARNESS_EMBED_BROWSER_EXTENSION`, and `build.rs` includes the built
//! extension's files here (see `build/browser_extension.rs`), so a CLI-only
//! install can set Chrome up. Other builds carry no files.
use anyhow::{Context as _, Result, bail};
use serde_json::Value;
use std::{fs, path::Path};

/// Files by their `/`-separated name inside the extension, sorted.
pub(crate) type Table = &'static [(&'static str, &'static [u8])];

mod generated {
    include!(concat!(env!("OUT_DIR"), "/browser_extension.rs"));
}

/// This executable's copy; empty unless it is a release build.
pub(crate) fn files() -> Table {
    generated::FILES
}

/// The embedded extension's `version_name` (its workspace version), else `version`.
pub(crate) fn version(table: Table) -> Option<String> {
    let (_, manifest) = table.iter().find(|(name, _)| *name == "manifest.json")?;
    let manifest: Value = serde_json::from_slice(manifest).ok()?;
    manifest["version_name"]
        .as_str()
        .or_else(|| manifest["version"].as_str())
        .map(str::to_owned)
}

/// Writes every file under `folder`, which must not exist yet.
pub(crate) fn write(table: Table, folder: &Path) -> Result<()> {
    fs::create_dir(folder).with_context(|| format!("cannot create {}", folder.display()))?;
    for (name, bytes) in table {
        let mut path = folder.to_path_buf();
        for part in name.split('/') {
            if matches!(part, "" | "." | "..") || part.contains('\\') {
                bail!("the embedded extension has an unusable file name: {name}");
            }
            path.push(part);
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("cannot create {}", parent.display()))?;
        }
        fs::write(&path, bytes).with_context(|| format!("cannot write {}", path.display()))?;
    }
    Ok(())
}

#[cfg(test)]
#[path = "../../build/browser_extension.rs"]
mod generator;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::browser::discovery::tests::temp;

    fn fixture(name: &str) -> std::path::PathBuf {
        let root = temp(name);
        fs::create_dir_all(root.join("assets/icons")).unwrap();
        fs::write(
            root.join("manifest.json"),
            br#"{"version":"0.1.1.1","version_name":"0.1.1-preview.1"}"#,
        )
        .unwrap();
        fs::write(root.join("background.js"), b"// worker").unwrap();
        fs::write(root.join("assets/icons/16.png"), b"png").unwrap();
        fs::write(root.join("assets/popup 1.js"), b"// spaced").unwrap();
        // Windows allows no quotes in names; its paths' backslashes need escaping instead.
        #[cfg(unix)]
        fs::write(root.join("assets/popup \"x\".js"), b"// quoted").unwrap();
        root
    }

    #[test]
    fn the_generator_includes_every_file_by_its_name_inside_the_extension() {
        let root = fixture("embed-files");
        let files = generator::files(&root).unwrap();
        let names: Vec<_> = files.iter().map(|file| file.name.as_str()).collect();
        let mut expected = vec![
            "assets/icons/16.png",
            "assets/popup 1.js",
            "background.js",
            "manifest.json",
        ];
        if cfg!(unix) {
            expected.insert(1, "assets/popup \"x\".js");
        }
        assert_eq!(names, expected);
        assert!(
            files
                .iter()
                .all(|file| Path::new(&file.path).is_absolute() && fs::read(&file.path).is_ok())
        );
        let source = generator::source(&root).unwrap();
        assert!(source.starts_with("// Generated by build.rs"), "{source}");
        assert!(source.contains("pub(crate) static FILES: &[(&str, &[u8])] = &[\n"));
        // Names and paths are Rust string literals, quotes and backslashes escaped.
        for file in &files {
            let line = format!("({:?}, include_bytes!({:?})),", file.name, file.path);
            assert!(source.contains(&line), "{line}\n{source}");
        }
        #[cfg(unix)]
        assert!(
            source.contains(r#"("assets/popup \"x\".js", include_bytes!("#),
            "{source}"
        );
        assert_eq!(source.matches("include_bytes!").count(), expected.len());
        assert!(generator::empty().ends_with("&[\n];\n"));
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn the_generator_refuses_what_is_not_a_built_extension() {
        let root = fixture("embed-refused");
        assert!(
            generator::files(Path::new("relative/dist/chrome"))
                .unwrap_err()
                .contains("absolute path")
        );
        let empty = root.join("empty");
        fs::create_dir_all(&empty).unwrap();
        assert!(
            generator::files(&empty)
                .unwrap_err()
                .contains("no manifest.json")
        );
        #[cfg(unix)]
        {
            std::os::unix::fs::symlink("/etc/hosts", root.join("assets/hosts")).unwrap();
            assert!(
                generator::files(&root)
                    .unwrap_err()
                    .contains("link or special file")
            );
            fs::remove_file(root.join("assets/hosts")).unwrap();
            std::os::unix::fs::symlink(&empty, root.join("linked")).unwrap();
            assert!(generator::files(&root).is_err(), "a linked folder too");
            fs::remove_file(root.join("linked")).unwrap();
        }
        let big = fs::File::create(root.join("big.bin")).unwrap();
        big.set_len(generator::MAX_BYTES).unwrap();
        assert!(
            generator::files(&root)
                .unwrap_err()
                .contains("more than 8388608 bytes")
        );
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn an_embedded_table_reports_its_version_and_writes_its_files() {
        static TABLE: &[(&str, &[u8])] = &[
            ("assets/icons/16.png", b"png"),
            ("background.js", b"// worker"),
            (
                "manifest.json",
                br#"{"version":"0.1.1.1","version_name":"0.1.1-preview.1"}"#,
            ),
        ];
        assert_eq!(version(TABLE).as_deref(), Some("0.1.1-preview.1"));
        assert_eq!(version(&[]), None);
        let root = temp("embed-write");
        fs::create_dir_all(&root).unwrap();
        let folder = root.join("Haarness for Chrome");
        write(TABLE, &folder).unwrap();
        assert_eq!(
            fs::read(folder.join("assets/icons/16.png")).unwrap(),
            b"png"
        );
        assert_eq!(
            fs::read(folder.join("background.js")).unwrap(),
            b"// worker"
        );
        assert!(write(TABLE, &folder).is_err(), "only into a new folder");
        assert!(write(&[("../outside.js", b"x")], &root.join("other")).is_err());
        assert!(!root.join("outside.js").exists());
        fs::remove_dir_all(root).unwrap();
    }
}
